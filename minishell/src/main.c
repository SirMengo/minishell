void	free_cmds(void *ptr)
{
	t_args	*args;

	if (!ptr)
		return ;
	args = (t_args *)ptr;
	if (args->content)
		free(args->content);
	if (args->type)
	{
		free(args->type);
	}
	free(args);
}

void	print_valueandtype(t_list *cmds)
{
	t_list	*current;
	t_args	*cmd;
	int		i;

	current = cmds;
	while (current)
	{
		cmd = (t_args *)current->content;
		if (cmd)
		{
			if (cmd->content)
			{
				printf("Content:\n");
				i = 0;
				while (cmd->content[i])
				{
					printf("  content[%d]: (%s)\n", i, cmd->content[i]);
					i++;
				}
			}
			if (cmd->type)
			{
				printf("Type:\n");
				i = 0;
				while (cmd->type[i])
				{
					printf("  type[%d]: (%s)\n", i, cmd->type[i]);
					i++;
				}
			}
		}
		current = current->next;
	}
}

